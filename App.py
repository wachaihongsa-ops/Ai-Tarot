import streamlit as st
import random

st.set_page_config(
    page_title="AI Tarot",
    page_icon="🔮"
)

cards = [
    "The Sun",
    "The Moon",
    "The Star",
    "The Fool"
]

st.title("🔮 AI Tarot")

topic = st.selectbox(
    "เลือกหัวข้อที่ต้องการดูดวง",
    ["การงาน", "การเงิน", "ความรัก"]
)

if st.button("🎴 Draw Card"):

    card = random.choice(cards)

    st.success(f"ไพ่ที่ได้: {card}")

    st.write("## 🔮 คำทำนาย")

    # ---------------------------
    # THE SUN
    # ---------------------------
    if card == "The Sun":

        st.markdown("""
### 🌞 The Sun

#### 💼 การงาน
- มีโอกาสได้รับข่าวดีเกี่ยวกับงาน
- ได้รับการยอมรับจากหัวหน้าหรือเพื่อนร่วมงาน
- โปรเจกต์ที่ทำอยู่มีแนวโน้มสำเร็จ

#### 💰 การเงิน
- รายได้มีแนวโน้มเพิ่มขึ้น
- มีโอกาสได้รับผลตอบแทนจากสิ่งที่ลงทุนไว้

#### ❤️ ความรัก
- ความสัมพันธ์มีความชัดเจนมากขึ้น
- เป็นช่วงเวลาที่ดีในการสื่อสาร

#### ✅ คำแนะนำ
ใช้ความมั่นใจและพลังบวกให้เต็มที่
""")

    # ---------------------------
    # THE MOON
    # ---------------------------
    elif card == "The Moon":

        st.markdown("""
### 🌙 The Moon

#### 💼 การงาน
- มีเรื่องที่ยังไม่ชัดเจน
- ควรตรวจสอบข้อมูลให้ละเอียด

#### 💰 การเงิน
- ระวังรายจ่ายที่ไม่คาดคิด
- อย่าตัดสินใจลงทุนด้วยอารมณ์

#### ❤️ ความรัก
- อาจเกิดความเข้าใจผิดได้ง่าย
- ควรพูดคุยกันตรง ๆ

#### ✅ คำแนะนำ
ใช้สติและความรอบคอบก่อนตัดสินใจ
""")

    # ---------------------------
    # THE STAR
    # ---------------------------
    elif card == "The Star":

        st.markdown("""
### ⭐ The Star

#### 💼 การงาน
- มีโอกาสใหม่เข้ามา
- สิ่งที่คาดหวังเริ่มมีความก้าวหน้า

#### 💰 การเงิน
- สถานการณ์การเงินมีแนวโน้มดีขึ้น
- อาจมีรายได้เพิ่มเติม

#### ❤️ ความรัก
- มีความหวังและพัฒนาการที่ดี
- ความสัมพันธ์ค่อย ๆ ดีขึ้น

#### ✅ คำแนะนำ
เชื่อมั่นในตัวเองและเดินหน้าต่อ
""")

    # ---------------------------
    # THE FOOL
    # ---------------------------
    elif card == "The Fool":

        st.markdown("""
### 🃏 The Fool

#### 💼 การงาน
- เหมาะกับการเริ่มต้นสิ่งใหม่
- อาจได้เรียนรู้ประสบการณ์ใหม่

#### 💰 การเงิน
- มีโอกาสใหม่ด้านการเงิน
- ควรวางแผนก่อนใช้จ่าย

#### ❤️ ความรัก
- เปิดใจรับคนใหม่หรือโอกาสใหม่
- อย่ากลัวการเริ่มต้น

#### ✅ คำแนะนำ
กล้าก้าวออกจาก Comfort Zone
""")